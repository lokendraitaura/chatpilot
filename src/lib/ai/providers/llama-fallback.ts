import { PromptTemplate } from "@langchain/core/prompts";
import { BaseAIProvider } from "./base";
import { GenerationOptions } from "../types";

export class Llama3FallbackProvider extends BaseAIProvider {
  name = "llama-fallback";

  async generate(template: PromptTemplate<any, any>, options: GenerationOptions): Promise<string> {
    const fallbackUrl = process.env.FALLBACK_LLAMA_URL;
    if (!fallbackUrl) {
      throw new Error("FALLBACK_LLAMA_URL is not configured.");
    }
    
    const formattedPrompt = await template.format(options);
    
    // Assuming structure matches Ollama or a generic text generation endpoint
    const response = await fetch(fallbackUrl, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        model: process.env.FALLBACK_LLAMA_MODEL || "llama3",
        prompt: formattedPrompt,
        stream: false
      })
    });
    
    if (!response.ok) {
        throw new Error(`Fallback API failed with status: ${response.status}`);
    }
    
    const data = await response.json();
    
    // Support Ollama format ('response') and OpenAI format ('choices')
    return data.response || data.choices?.[0]?.text || data.choices?.[0]?.message?.content || "No response generated by fallback.";
  }
}
